// Postbuild step (runs after csp:hash). Reads the finalized hash-based CSP from
// dist/_headers and writes it to functions/_csp.generated.js, so the Cloudflare
// Pages Function (functions/_middleware.js) emits the exact per-build CSP.
//
// Needed because the CSP (~3.1KB) exceeds Cloudflare Pages' 2000-char-per-line
// limit in the static _headers file, and _headers does not apply to responses
// served through a Function - so the middleware sets every security header.
//
// Host-agnostic: on Netlify this just writes an unused file (Netlify ignores
// functions/), so it is safe to run on either host during the migration window.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const HEADERS_PATH = resolve(__dirname, '../dist/_headers')
const OUT_PATH = resolve(__dirname, '../functions/_csp.generated.js')

if (!existsSync(HEADERS_PATH)) {
  console.error('✗ generate-cf-headers: dist/_headers not found (run after csp:hash).')
  process.exit(1)
}

const text = readFileSync(HEADERS_PATH, 'utf8')
const match = text.match(/^\s*Content-Security-Policy:\s*(.+)$/m)
if (!match) {
  console.error('✗ generate-cf-headers: no Content-Security-Policy line in dist/_headers.')
  process.exit(1)
}

const csp = match[1].trim()
writeFileSync(
  OUT_PATH,
  '// AUTO-GENERATED by scripts/generate-cf-headers.mjs (postbuild). Do not edit.\n' +
    '// The hash CSP (~3.1KB) exceeds Cloudflare Pages _headers 2000-char/line cap,\n' +
    '// so it is emitted from functions/_middleware.js instead.\n' +
    `export const CSP = ${JSON.stringify(csp)}\n`,
)
console.log(`✓ functions/_csp.generated.js written (CSP ${csp.length} chars)`)
